-- Миграция 6: роль владельца сайта
-- Запускать можно многократно.

SET client_encoding TO 'UTF8';

-- ==========================================================
-- Владелец сайта.
--
-- Отличается от админа тем, что его нельзя удалить и нельзя понизить
-- в правах — иначе можно остаться без доступа к управлению сайтом.
-- Владелец назначается один раз: это первый зарегистрированный аккаунт.
-- ==========================================================

-- Первый по порядку пользователь становится владельцем,
-- если владельца ещё нет
UPDATE users
   SET role = 'owner'
 WHERE id = (SELECT MIN(id) FROM users)
   AND NOT EXISTS (SELECT 1 FROM users WHERE role = 'owner');

SELECT id, name, email, role FROM users ORDER BY id;
